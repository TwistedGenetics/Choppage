#!/bin/sh
# Regenerates choppage-mpc/src/core_*.cpp: one wrapper per choppage-core source (the SDK's build.py compiles
# src/*.cpp only). Run after adding or removing a file in choppage-core/src.
set -e
cd "$(dirname "$0")/.."
rm -f src/core_*.cpp src/app_*.cpp
for f in ../choppage-core/src/*.cpp; do
  b=$(basename "$f" .cpp)
  printf '// Generated by tools/sync_core.sh: compiles choppage-core/src/%s.cpp into the MPC plugin.\n#include "../../choppage-core/src/%s.cpp"\n' "$b" "$b" > "src/core_$b.cpp"
done
printf '// Generated by tools/sync_core.sh.\n#include "../app/ChoppageMpcApp.cpp"\n' > src/app_ChoppageMpcApp.cpp
echo "wrappers: $(ls src/core_*.cpp | wc -l) core sources"
